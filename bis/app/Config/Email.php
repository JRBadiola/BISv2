<?php

namespace Config;

use CodeIgniter\Config\BaseConfig;

class Email extends BaseConfig
{
    /**
     * --------------------------------------------------------------------
     * Mail Protocol
     * --------------------------------------------------------------------
     */
    public string $protocol = 'smtp';

    /**
     * --------------------------------------------------------------------
     * SMTP Host
     * --------------------------------------------------------------------
     */
    public string $SMTPHost = '';

    /**
     * --------------------------------------------------------------------
     * SMTP Username
     * --------------------------------------------------------------------
     */
    public string $SMTPUser = '';

    /**
     * --------------------------------------------------------------------
     * SMTP Password
     * --------------------------------------------------------------------
     */
    public string $SMTPPass = '';

    /**
     * --------------------------------------------------------------------
     * SMTP Port
     * --------------------------------------------------------------------
     */
    public int $SMTPPort = 587;

    /**
     * --------------------------------------------------------------------
     * SMTP Encryption
     * --------------------------------------------------------------------
     */
    public string $SMTPCrypto = 'tls';

    /**
     * --------------------------------------------------------------------
     * From Email
     * --------------------------------------------------------------------
     */
    public string $fromEmail = '';

    /**
     * --------------------------------------------------------------------
     * From Name
     * --------------------------------------------------------------------
     */
    public string $fromName = 'BIS';

    /**
     * --------------------------------------------------------------------
     * Email Type
     * --------------------------------------------------------------------
     */
    public string $mailType = 'html';

    /**
     * --------------------------------------------------------------------
     * Character Set
     * --------------------------------------------------------------------
     */
    public string $charset = 'UTF-8';

    /**
     * --------------------------------------------------------------------
     * Word Wrap
     * --------------------------------------------------------------------
     */
    public bool $wordWrap = true;

    /**
     * --------------------------------------------------------------------
     * Newline
     * --------------------------------------------------------------------
     */
    public string $newline = "\r\n";

    /**
     * --------------------------------------------------------------------
     * CRLF
     * --------------------------------------------------------------------
     */
    public string $CRLF = "\r\n";

    /**
     * --------------------------------------------------------------------
     * Validate
     * --------------------------------------------------------------------
     */
    public bool $validate = true;

    public function __construct()
    {
        parent::__construct();

        $this->protocol = env('email.protocol', 'smtp');

        $this->SMTPHost = env(
            'email.SMTPHost',
            'smtp.gmail.com'
        );

        $this->SMTPUser = env(
            'email.SMTPUser',
            ''
        );

        $this->SMTPPass = env(
            'email.SMTPPass',
            ''
        );

        $this->SMTPPort = (int) env(
            'email.SMTPPort',
            587
        );

        $this->SMTPCrypto = env(
            'email.SMTPCrypto',
            'tls'
        );

        $this->fromEmail = env(
            'email.fromEmail',
            ''
        );

        $this->fromName = env(
            'email.fromName',
            'BIS'
        );

        $this->mailType = env(
            'email.mailType',
            'html'
        );

        $this->charset = env(
            'email.charset',
            'UTF-8'
        );

        $this->wordWrap = filter_var(
            env('email.wordWrap', true),
            FILTER_VALIDATE_BOOLEAN
        );
    }
}